var DataUnavailableError = class extends Error {};
/**
* 数据面路由处理函数（GET 读全量 / POST 写全量并落盘）。
* dataPath 由调用方传入：apply 传 DATA_PATH，测试传临时目录，避免读写开发者主目录。
*/
function createDataRoute(dataPath) {
	/**
	* 读落盘数据：
	* - ENOENT → 默认数据，不产生备份
	* - 损坏（JSON 解析失败，或 prompts 非数组 / usage 非对象）→ 原文件重命名为 data.json.corrupt-<时间戳>，再返回默认数据。
	*   判定沿用宽松条件：严格校验会让一条手改的带空格缩写导致整个文件被备份
	* - 其他读错误、重命名失败 → DataUnavailableError（路由返回 500，后续不写入）
	*/
	const readData = async () => {
		let text;
		try {
			text = await readFile(dataPath, "utf8");
		} catch (err) {
			if (err.code === "ENOENT") return structuredClone(DEFAULT_DATA);
			console.error("[dsh-quick-prompts] read data failed:", err);
			throw new DataUnavailableError("read failed");
		}
		let raw;
		try {
			raw = JSON.parse(text);
		} catch {
			raw = void 0;
		}
		if (raw && Array.isArray(raw.prompts) && typeof raw.usage === "object" && raw.usage !== null) return {
			prompts: raw.prompts,
			usage: raw.usage,
			listSortMode: parseListSortMode(raw.listSortMode)
		};
		const backup = `${dataPath}.corrupt-${(/* @__PURE__ */ new Date()).toISOString().replace(/[:.]/g, "-")}`;
		try {
			await rename(dataPath, backup);
		} catch (err) {
			console.error("[dsh-quick-prompts] backup corrupt data failed:", err);
			throw new DataUnavailableError("backup failed");
		}
		console.error(`[dsh-quick-prompts] data file corrupt, moved to ${backup}`);
		return structuredClone(DEFAULT_DATA);
	};
	/** 原子写：唯一临时文件 + rename。临时文件名带 UUID，并发或残留都不会互相覆盖；失败时删掉临时文件再抛出 */
	const writeData = async (data) => {
		await mkdir(dirname(dataPath), { recursive: true });
		const tmp = `${dataPath}.${randomUUID()}.tmp`;
		try {
			await writeFile(tmp, JSON.stringify(data, null, 2), "utf8");
			await rename(tmp, dataPath);
		} catch (err) {
			await rm(tmp, { force: true }).catch(() => {});
			throw err;
		}
	};
	let queue = Promise.resolve();
	const serial = (task) => {
		const run = queue.then(task, task);
		queue = run.catch(() => {});
		return run;
	};
	const handlePost = (request) => serial(async () => {
		let body;
		try {
			body = await request.json();
		} catch {
			return Response.json({
				ok: false,
				error: "invalid JSON"
			}, {
				status: 400,
				headers: NO_STORE
			});
		}
		const invalid = validateDataBody(body);
		if (invalid !== void 0) return Response.json({
			ok: false,
			error: invalid
		}, {
			status: 400,
			headers: NO_STORE
		});
		const patch = body;
		const current = await readData();
		try {
			await writeData({
				prompts: patch.prompts ?? current.prompts,
				usage: patch.usage ?? current.usage,
				listSortMode: parseListSortMode(patch.listSortMode ?? current.listSortMode)
			});
		} catch (err) {
			console.error("[dsh-quick-prompts] write data failed:", err);
			return Response.json({
				ok: false,
				error: "write failed"
			}, {
				status: 500,
				headers: NO_STORE
			});
		}
		return Response.json({ ok: true }, { headers: NO_STORE });
	});
	return async (request) => {
		try {
			if (request.method === "POST") return await handlePost(request);
			return await serial(async () => Response.json(await readData(), { headers: NO_STORE }));
		} catch (err) {
			if (err instanceof DataUnavailableError) return Response.json({
				ok: false,
				error: "data unavailable"
			}, {
				status: 500,
				headers: NO_STORE
			});
			throw err;
		}
	};
}
